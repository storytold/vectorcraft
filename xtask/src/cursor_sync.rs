//! `cargo xtask cursors NIBCRAFT`: bring the designers' cursor drawings in, by id.
//!
//! The manifest (`crates/tools/src/cursors.toml`) says which cursors designers draw. For each one,
//! nibcraft (`nibcraft glyphs PROJECT ID…`) answers with its generated glyph, or says it isn't
//! drawn yet or doesn't convert. This rewrites the generated part of
//! `crates/ui-egui/src/cursors/glyphs.rs` (the `GENERATED` table, in `Cursor` order, and the
//! glyph `const`s) and prints what changed and the designers' notes. A cursor whose drawing is
//! gone is unwired and falls back; one whose new drawing doesn't convert keeps its previous glyph.
//! Nothing is committed.

use crate::cursors::{self, Variant};
use serde_json::Value;
use std::path::Path;
use std::process::Command;

pub const GLYPHS: &str = "crates/ui-egui/src/cursors/glyphs.rs";
const TABLE_START: &str = "pub(super) const GENERATED: &[(Cursor, &Glyph)] = &[\n";
const TABLE_END: &str = "\n];\n";
const CONSTS_MARK: &str = "\n// Generated glyphs";
const TESTS_MARK: &str = "\n#[cfg(test)]";
const CONST_START: &str = "/// Generated by nibcraft from its `";

pub fn run(root: &Path, nibcraft: &Path, enum_src: &str, manifest: &str) -> Result<(), String> {
    let cc = nibcraft.canonicalize().map_err(|e| format!("{}: {e}", nibcraft.display()))?;
    let variants = cursors::variants(enum_src);
    let entries = cursors::entries(manifest);
    let wanted: Vec<&Variant> = variants.iter().filter(|v| entries.iter().any(|e| e.designer && e.id.as_deref() == Some(v.name.as_str()))).collect();
    let project = cursors::app(manifest).unwrap_or_else(|| "VectorCraft".into()).to_lowercase();
    let answer = parse_answer(&ask(&cc, &project, &wanted)?)?;
    let path = root.join(GLYPHS);
    let old = std::fs::read_to_string(&path).map_err(|e| format!("{GLYPHS}: {e}"))?;
    let (text, report) = sync(&old, &answer, &wanted)?;
    if text != old {
        std::fs::write(&path, &text).map_err(|e| format!("{GLYPHS}: {e}"))?;
    }
    print!("{}", report.render(&answer, text != old));
    Ok(())
}

/// Run `nibcraft glyphs PROJECT ID…` in nibcraft's folder and return its JSON.
fn ask(cc: &Path, project: &str, wanted: &[&Variant]) -> Result<String, String> {
    let mut cmd = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()));
    cmd.current_dir(cc)
        .env_remove("CARGO_TARGET_DIR")
        .args(["run", "-q", "--manifest-path"])
        .arg(cc.join("Cargo.toml"))
        .args(["--", "glyphs", project]);
    cmd.args(wanted.iter().map(|v| v.name.as_str()));
    let out = cmd.output().map_err(|e| format!("couldn't run nibcraft in {}: {e}", cc.display()))?;
    if !out.status.success() {
        return Err(format!("nibcraft glyphs failed in {}:\n{}", cc.display(), String::from_utf8_lossy(&out.stderr).trim()));
    }
    String::from_utf8(out.stdout).map_err(|e| format!("nibcraft's answer isn't text: {e}"))
}

/// A drawn cursor in nibcraft's answer.
pub struct Drawn {
    id: String,
    konst: String,
    fp: String,
    code: String,
}

/// nibcraft's answer to `glyphs`.
pub struct Answer {
    source: String,
    pulled: String,
    notes: String,
    drawn: Vec<Drawn>,
    errors: Vec<(String, String)>,
}

fn parse_answer(json: &str) -> Result<Answer, String> {
    let v: Value = serde_json::from_str(json).map_err(|e| format!("nibcraft's answer isn't JSON: {e}"))?;
    let s = |v: &Value, k: &str| v.get(k).and_then(Value::as_str).unwrap_or_default().to_string();
    let list = |k: &str| v.get(k).and_then(Value::as_array).cloned().unwrap_or_default();
    let drawn = list("glyphs")
        .iter()
        .map(|g| Drawn { id: s(g, "id"), konst: s(g, "const"), fp: s(g, "fp"), code: s(g, "code") })
        .filter(|d| !d.id.is_empty() && !d.konst.is_empty() && d.code.starts_with(CONST_START))
        .collect();
    let errors = list("errors").iter().map(|e| (s(e, "id"), s(e, "error"))).collect();
    Ok(Answer { source: s(&v, "source"), pulled: s(&v, "pulled"), notes: s(&v, "notes").trim().to_string(), drawn, errors })
}

/// A generated `const` already in `glyphs.rs`.
struct Const {
    id: String,
    konst: String,
    fp: String,
    code: String,
}

/// The generated `const`s in `region`, each from its doc comment to its closing `};`.
fn consts(region: &str) -> Vec<Const> {
    let mut out = vec![];
    let mut current: Option<String> = None;
    for line in region.split_inclusive('\n') {
        if line.starts_with(CONST_START) {
            current = Some(String::new());
        }
        let Some(code) = current.as_mut() else { continue };
        code.push_str(line);
        if line.trim_end() == "};" {
            let field = |key: &str| code.split_once(key).and_then(|(_, rest)| rest.split('"').next()).unwrap_or_default().to_string();
            let konst = code.lines().find_map(|l| l.strip_prefix("const ")?.split(':').next()).unwrap_or_default().to_string();
            out.push(Const { id: field("    id: \""), fp: field(", fp: \""), konst, code: code.clone() });
            current = None;
        }
    }
    out
}

/// What a sync changed.
#[derive(Default, Debug, PartialEq)]
pub struct Report {
    new: Vec<String>,
    redrawn: Vec<String>,
    unwired: Vec<String>,
    /// Drawings that don't convert: (id, error, whether the previous glyph was kept).
    broken: Vec<(String, String, bool)>,
    not_drawn: Vec<String>,
    notes_changed: bool,
}

/// `old`'s text with its generated part rewritten from `answer`, and what changed.
fn sync(old: &str, answer: &Answer, wanted: &[&Variant]) -> Result<(String, Report), String> {
    let missing = |what: &str| format!("{GLYPHS}: can't find {what}; was the file reorganised?");
    let table = old.find(TABLE_START).ok_or_else(|| missing("the GENERATED table"))? + TABLE_START.len();
    let table_end = table + old[table..].find(TABLE_END).ok_or_else(|| missing("the end of the GENERATED table"))?;
    let mark = table_end + old[table_end..].find(CONSTS_MARK).ok_or_else(|| missing("the `// Generated glyphs` line"))? + 1;
    let tests = mark + old[mark..].find(TESTS_MARK).ok_or_else(|| missing("the tests"))? + 1;
    let region = &old[mark..tests];
    let before = consts(region);
    let old_notes = region
        .lines()
        .next()
        .and_then(|l| l.split("designer notes ").nth(1))
        .and_then(|s| s.split(|c: char| !c.is_ascii_alphanumeric()).next())
        .unwrap_or_default();

    let mut r = Report::default();
    let mut rows: Vec<(&Variant, String, String)> = vec![];
    for v in wanted {
        let id = v.name.as_str();
        let prev = before.iter().find(|c| c.id == id);
        if let Some(d) = answer.drawn.iter().find(|d| d.id == id) {
            match prev {
                None => r.new.push(id.into()),
                Some(p) if p.fp != d.fp => r.redrawn.push(id.into()),
                Some(_) => {}
            }
            rows.push((v, d.konst.clone(), d.code.clone()));
        } else if let Some((_, e)) = answer.errors.iter().find(|(i, _)| i == id) {
            r.broken.push((id.into(), e.clone(), prev.is_some()));
            if let Some(p) = prev {
                rows.push((v, p.konst.clone(), p.code.clone()));
            }
        } else if prev.is_some() {
            r.unwired.push(id.into());
        } else {
            r.not_drawn.push(id.into());
        }
    }
    r.unwired.extend(before.iter().filter(|c| !wanted.iter().any(|v| v.name == c.id)).map(|c| c.id.clone()));

    let notes = notes_fp(&answer.notes);
    r.notes_changed = notes != old_notes;
    let table_rows: String =
        rows.iter()
            .map(|(v, k, _)| {
                if v.has_value {
                    format!("    (Cursor::{}(super::{k}_DRAWN), &{k}),\n", v.name)
                } else {
                    format!("    (Cursor::{}, &{k}),\n", v.name)
                }
            })
            .collect();
    let code: Vec<&str> = rows.iter().map(|(_, _, c)| c.as_str()).collect();
    let source = if answer.source.is_empty() { "unknown" } else { answer.source.as_str() };
    let text = format!(
        "{}{}{}// Generated glyphs: written by `cargo xtask cursors` from nibcraft {source}; designer notes {notes}. Don't edit them by hand.\n\n{}\n{}",
        &old[..table],
        table_rows.trim_end_matches('\n'),
        &old[table_end..mark],
        code.join("\n"),
        &old[tests..]
    );
    Ok((text, r))
}

/// A short fingerprint of the designers' notes (`none` when there are none), so a sync can tell
/// whether they changed since the last one.
fn notes_fp(notes: &str) -> String {
    if notes.is_empty() { "none".into() } else { crate::sha256::hex(notes.as_bytes()).chars().take(8).collect() }
}

impl Report {
    fn render(&self, answer: &Answer, changed: bool) -> String {
        let mut out = format!("cursors: synced from nibcraft {}", answer.source);
        if !answer.pulled.is_empty() {
            out.push_str(&format!(" (its list pulled from {})", answer.pulled));
        }
        out.push('\n');
        let list = |out: &mut String, label: &str, ids: &[String]| {
            if !ids.is_empty() {
                out.push_str(&format!("  {label} ({}): {}\n", ids.len(), ids.join(", ")));
            }
        };
        list(&mut out, "new", &self.new);
        list(&mut out, "redrawn", &self.redrawn);
        list(&mut out, "unwired (drawing gone; falls back)", &self.unwired);
        for (id, e, kept) in &self.broken {
            let what = if *kept { "kept its previous glyph" } else { "not wired" };
            out.push_str(&format!("  {id}: the drawing doesn't convert, {what}: {e}\n"));
        }
        list(&mut out, "not drawn yet", &self.not_drawn);
        if !changed {
            out.push_str("  nothing to change in glyphs.rs\n");
        }
        match (answer.notes.is_empty(), self.notes_changed) {
            (true, _) => out.push_str("\nNo designer notes.\n"),
            (false, changed) => {
                let when = if changed { "new since the last sync" } else { "unchanged since the last sync" };
                out.push_str(&format!("\nDesigner notes ({when}):\n\n{}\n", answer.notes));
            }
        }
        if changed {
            out.push_str("\nNext: `cargo xtask ci`, look at the cursors in the app, then commit.\n");
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn glyph(id: &str, fp: &str) -> String {
        let k = id.to_uppercase();
        format!(
            "{CONST_START}{id}` cursor ({fp}). Don't edit by hand.\n#[rustfmt::skip]\nconst {k}: Glyph = Glyph {{\n    id: \"{id}\", fp: \"{fp}\", data_fp: \"00000000\",\n    parts: &[],\n}};\n"
        )
    }

    fn file(rows: &str, consts: &[String], notes: &str) -> String {
        format!(
            "//! Head.\n\n{TABLE_START}{rows}\n];\n\nfn generated() {{}}\n\n// Generated glyphs: written by `cargo xtask cursors` from nibcraft old; designer notes {notes}. Don't edit them by hand.\n\n{}\n#[cfg(test)]\nmod tests {{}}\n",
            consts.join("\n")
        )
    }

    fn variant(name: &str, has_value: bool) -> Variant {
        Variant { name: name.into(), has_value }
    }

    fn answer(drawn: &[(&str, &str)], errors: &[(&str, &str)], notes: &str) -> Answer {
        Answer {
            source: "abc1234".into(),
            pulled: "VectorCraft 0.10.0 (fdd65793, 2026-10-13)".into(),
            notes: notes.into(),
            drawn: drawn.iter().map(|(id, fp)| Drawn { id: (*id).into(), konst: id.to_uppercase(), fp: (*fp).into(), code: glyph(id, fp) }).collect(),
            errors: errors.iter().map(|(i, e)| ((*i).into(), (*e).into())).collect(),
        }
    }

    #[test]
    fn rewrites_the_table_in_enum_order_and_reports_each_change() {
        let old = file(
            "    (Cursor::Pen, &PEN),\n    (Cursor::Knife, &KNIFE),\n    (Cursor::Gone, &GONE),",
            &[glyph("Pen", "1"), glyph("Knife", "2"), glyph("Gone", "3"), glyph("Arrow", "4")],
            "none",
        );
        let (arrow, turn, pen, knife, lasso, wand) = (
            variant("Arrow", false),
            variant("Turn", true),
            variant("Pen", false),
            variant("Knife", false),
            variant("Lasso", false),
            variant("Wand", false),
        );
        let wanted = [&arrow, &turn, &pen, &knife, &lasso, &wand];
        let a = answer(&[("Turn", "5"), ("Pen", "9"), ("Arrow", "4")], &[("Knife", "no hotspot"), ("Wand", "bad SVG")], "");
        let (text, r) = sync(&old, &a, &wanted).unwrap();
        assert!(text.contains(&format!("{TABLE_START}    (Cursor::Arrow, &ARROW),\n    (Cursor::Turn(super::TURN_DRAWN), &TURN),\n    (Cursor::Pen, &PEN),\n    (Cursor::Knife, &KNIFE),\n];\n")), "{text}");
        assert!(text.contains("from nibcraft abc1234; designer notes none."), "{text}");
        assert!(text.contains(&glyph("Pen", "9")) && text.contains(&glyph("Knife", "2")) && !text.contains("GONE"), "{text}");
        assert!(
            text.starts_with("//! Head.\n") && text.contains("\nfn generated() {}\n") && text.ends_with("\n};\n\n#[cfg(test)]\nmod tests {}\n"),
            "{text}"
        );
        assert_eq!(r.new, ["Turn"]);
        assert_eq!(r.redrawn, ["Pen"]);
        assert_eq!(r.unwired, ["Gone"]);
        assert_eq!(r.broken, [("Knife".into(), "no hotspot".into(), true), ("Wand".into(), "bad SVG".into(), false)]);
        assert_eq!(r.not_drawn, ["Lasso"]);
        assert!(!r.notes_changed);
    }

    #[test]
    fn a_second_sync_of_the_same_answer_changes_nothing() {
        let pen = variant("Pen", false);
        let a = answer(&[("Pen", "1")], &[], "Bolder nib?");
        let (once, r) = sync(&file("", &[], "none"), &a, &[&pen]).unwrap();
        assert!(r.notes_changed);
        let (twice, r) = sync(&once, &a, &[&pen]).unwrap();
        assert_eq!(once, twice);
        assert_eq!(r, Report::default());
        assert!(r.render(&a, false).contains("Designer notes (unchanged since the last sync):\n\nBolder nib?\n"));
    }

    #[test]
    fn a_reorganised_file_is_an_error_not_a_guess() {
        let pen = variant("Pen", false);
        assert!(sync("//! Nothing here.\n", &answer(&[], &[], ""), &[&pen]).unwrap_err().contains("GENERATED table"));
    }

    #[test]
    fn parses_nibcrafts_answer() {
        let json = format!(
            r#"{{"source": "abc", "pulled": "P", "notes": " N \n", "glyphs": [{{"id": "Pen", "const": "PEN", "fp": "1", "code": {}}}, {{"id": "X", "const": "X", "fp": "2", "code": "not a glyph"}}], "missing": ["Lasso"], "errors": [{{"id": "Knife", "error": "bad"}}]}}"#,
            serde_json::to_string(&glyph("Pen", "1")).unwrap()
        );
        let a = parse_answer(&json).unwrap();
        assert_eq!((a.source.as_str(), a.pulled.as_str(), a.notes.as_str()), ("abc", "P", "N"));
        assert_eq!(a.drawn.len(), 1, "code that isn't a generated glyph is refused");
        assert_eq!(a.errors, [("Knife".to_string(), "bad".to_string())]);
        assert!(parse_answer("oops").is_err());
    }
}
